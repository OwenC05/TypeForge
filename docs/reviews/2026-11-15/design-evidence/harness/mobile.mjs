import { BASE, launch, shot, note, saveLog, active, target, typeRun, savedResults } from './lib.mjs';
const [ud, ud320] = process.argv.slice(2);
const ctx = await launch(ud, { width: 390, height: 844 }, { isMobile: true, hasTouch: true, deviceScaleFactor: 2 });
const p = ctx.pages()[0] ?? await ctx.newPage();
const errors = []; p.on('pageerror', e => errors.push(e.message));
await p.goto(BASE + '/index.html'); await p.waitForSelector('.hero');
await shot(p, 'm01-home-390.png'); await shot(p, 'm02-home-390-full.png', { fullPage: true });
note('home overflow', { scrollW: await p.evaluate(() => document.documentElement.scrollWidth), clientW: await p.evaluate(() => document.documentElement.clientWidth) });
await p.tap('text=Just practise'); await p.waitForSelector('#typing-input'); await p.waitForTimeout(400);
await shot(p, 'm03-practice-idle-390.png'); await shot(p, 'm04-practice-idle-390-full.png', { fullPage: true });
const geo = await p.evaluate(() => { const r = s => { const b = document.querySelector(s).getBoundingClientRect(); return { top: Math.round(b.top), bottom: Math.round(b.bottom), height: Math.round(b.height) }; }; return { surface: r('#typing-viewport'), textarea: r('#typing-input'), timer: r('.practice-toolbar'), restart: r('#restart'), nav: r('nav'), scrollW: document.documentElement.scrollWidth }; });
note('mobile practice geometry (CSS px, viewport 390x844)', geo);
const ta = await p.locator('#typing-input').boundingBox();
await p.tap('#typing-input'); await p.waitForTimeout(200);
note('tap textarea', { active: await active(p), scrollY: await p.evaluate(() => scrollY) });
await p.selectOption('#duration', '15'); await p.waitForFunction(() => document.querySelector('#remaining')?.textContent === '15'); await p.waitForTimeout(300);
note('after select 15', { active: await active(p), scrollY: await p.evaluate(() => scrollY) });
setTimeout(async () => { try { await shot(p, 'm05-practice-running-390.png'); note('mobile mid-run', { scrollY: await p.evaluate(() => scrollY), surfaceTop: await p.evaluate(() => Math.round(document.querySelector('#typing-viewport').getBoundingClientRect().top)) }); } catch (e) { note('mid fail', { e: e.message }); } }, 7000);
const r = await typeRun(p, { delay: 110, errorAt: 4, onError: async pp => { await shot(pp, 'm06-practice-error-390.png'); } });
note('mobile 15s practice (simulated key events, not IME)', r);
await p.waitForSelector('#coach-title').catch(() => {}); await p.waitForTimeout(500);
await shot(p, 'm07-results-390.png'); await shot(p, 'm08-results-390-full.png', { fullPage: true });
note('results overflow', { scrollW: await p.evaluate(() => document.documentElement.scrollWidth) });
await p.goto(BASE + '/progress.html'); await p.waitForTimeout(600);
await shot(p, 'm09-progress-390-full.png', { fullPage: true });
await p.goto(BASE + '/lab.html'); await p.waitForTimeout(600);
await shot(p, 'm10-lab-390.png');
note('lab overflow', { scrollW: await p.evaluate(() => document.documentElement.scrollWidth) });
note('saved', { results: await savedResults(p) }); note('errors', { errors });
await ctx.close();
// 320px stress + 200% zoom approximation (1440 window at 200% ~ 720x450 CSS px)
for (const [w, h, tag] of [[320, 640, '320'], [720, 450, 'zoom200-approx']]) {
  const c = await launch(ud320 + tag, { width: w, height: h }, { deviceScaleFactor: 2 });
  const q = c.pages()[0] ?? await c.newPage();
  await q.goto(BASE + '/practice.html?mode=practice&practice=manual&pair=th'); await q.waitForSelector('#typing-input'); await q.waitForTimeout(400);
  await shot(q, `s-${tag}-practice.png`); await shot(q, `s-${tag}-practice-full.png`, { fullPage: true });
  note(`stress ${tag}`, await q.evaluate(() => ({ scrollW: document.documentElement.scrollWidth, clientW: document.documentElement.clientWidth, surfaceTop: Math.round(document.querySelector('#typing-viewport').getBoundingClientRect().top), focus: document.querySelector('#focus-state').textContent })));
  await q.goto(BASE + '/index.html'); await q.waitForTimeout(300); await shot(q, `s-${tag}-home.png`);
  await c.close();
}
saveLog('mobile-stress-log.json');
