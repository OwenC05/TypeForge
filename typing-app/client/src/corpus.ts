/**
 * Returns each unexcluded prompt once. An exhausted bank returns no prompts.
 * When cycling, exclude the last prompt as well to avoid a boundary repeat.
 * An injected random source must return values in [0, 1), like Math.random.
 */
export function selectPrompts(
  mode: 'assessment' | 'practice',
  excludeIds: string[] = [],
  random: () => number = Math.random,
): Prompt[] {
  const excluded = new Set(excludeIds);
  const prompts = (mode === 'assessment' ? assessmentPrompts : practicePrompts)
    .filter((prompt) => !excluded.has(prompt.id));
  for (let i = prompts.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1));
    [prompts[i], prompts[j]] = [prompts[j]!, prompts[i]!];
  }
  return prompts;
}
